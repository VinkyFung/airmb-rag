def load_js_data(path: Path):
    text = path.read_text(encoding="utf-8-sig")
    start = text.find("[")
    end = text.rfind("]")
    if start < 0 or end < start:
        raise ValueError("未找到 JSON 数组。")
    return json.loads(text[start : end + 1]), text[:start], text[end + 1 :]


def main() -> None:
    data, prefix, suffix = load_js_data(SOURCE_JS)
    target = next((category for category in data if category.get("title") == TARGET_TITLE), None)
    if target is None:
        raise ValueError(f"未找到分类：{TARGET_TITLE}")

    children = target.get("children", [])
    if len(children) != len(UPDATES):
        raise ValueError(f"目标 children 数量为 {len(children)}，更新数据数量为 {len(UPDATES)}。")

    backup = SOURCE_JS.with_name(f"{SOURCE_JS.name}.bak_{time.strftime('%Y%m%d_%H%M%S')}")
    shutil.copy2(SOURCE_JS, backup)

    for child, update in zip(children, UPDATES):
        child["variety"] = update["variety"]
        child["feature"] = update["feature"]
        if "mark" in update:
            child["mark"] = update["mark"]

    SOURCE_JS.write_text(prefix + json.dumps(data, ensure_ascii=False, indent=2) + suffix, encoding="utf-8")
    print(f"updated={len(children)} backup={backup}")


if __name__ == "__main__":
    main()
